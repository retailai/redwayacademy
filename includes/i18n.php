<?php
/**
 * Redway Academy — full bilingual support (Bangla + English).
 * Language is chosen with ?lang=bn|en, stored in a cookie (1 year) and the
 * session, and applied to the whole interface: nav, headings, buttons,
 * cards, dashboards, forms and lesson UI. Course titles/descriptions are
 * database content and stay as stored; every label around them translates.
 * Digits follow the language: Bengali digits in Bangla mode, Latin in EN.
 */
function current_lang(): string {
    if (isset($_GET['lang']) && in_array($_GET['lang'], ['bn', 'en'], true)) {
        $lang = $_GET['lang'];
        if (!headers_sent()) {
            setcookie('rw_lang', $lang, time() + 365 * 86400, '/', '', false, true);
        }
        $_COOKIE['rw_lang'] = $lang;
        if (session_status() === PHP_SESSION_ACTIVE) $_SESSION['rw_lang'] = $lang;
        return $lang;
    }
    if (!empty($_COOKIE['rw_lang']) && in_array($_COOKIE['rw_lang'], ['bn', 'en'], true)) return $_COOKIE['rw_lang'];
    if (!empty($_SESSION['rw_lang']) && in_array($_SESSION['rw_lang'], ['bn', 'en'], true)) return $_SESSION['rw_lang'];
    return 'bn'; // Bangla-first site.
}
function lang_is_bn(): bool { return current_lang() === 'bn'; }
function html_lang(): string { return current_lang(); }

/** Bengali digits when in Bangla mode; Latin digits in English mode. */
function num($n): string {
    $s = (string)$n;
    if (!lang_is_bn()) return $s;
    return strtr($s, ['0' => '০', '1' => '১', '2' => '২', '3' => '৩', '4' => '৪', '5' => '৫', '6' => '৬', '7' => '৭', '8' => '৮', '9' => '৯']);
}
function tk(int $n): string { return '৳' . num($n); }
/** Display "original" (pre-discount) price: current price + ৳300 launch offer. */
function orig_price(int $p): int { return $p + 300; }

/** Current URL with query params overridden (used by the language switcher). */
function url_with_query(array $over): string {
    $uri = $_SERVER['REQUEST_URI'] ?? '/';
    $parts = parse_url($uri);
    $q = [];
    if (!empty($parts['query'])) parse_str($parts['query'], $q);
    foreach ($over as $k => $v) $q[$k] = $v;
    $qs = http_build_query($q);
    return ($parts['path'] ?? '/') . ($qs !== '' ? '?' . $qs : '');
}

/** Translate a UI key. Falls back to English, then to the key itself. */
function t(string $key, array $vars = []): string {
    $lang = current_lang();
    $s = I18N[$lang][$key] ?? I18N['en'][$key] ?? $key;
    if ($vars) $s = vsprintf($s, $vars);
    return $s;
}

